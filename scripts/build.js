#!/usr/bin/env node
"use strict";

/**
 * @file build.js
 * @description Zero-dependency CommonJS bundler that packs `src/*.js` into a standalone `dist/agy-hud.js` file.
 */

const fs = require("node:fs");
const path = require("node:path");

const rootDir = path.resolve(__dirname, "..");
const srcDir = path.join(rootDir, "src");
const distFile = path.join(rootDir, "dist", "agy-hud.js");

const modules = [
  "ansi",
  "config",
  "gitinfo",
  "host",
  "session",
  "quota",
  "quotaProbe",
  "statusline",
  "main"
];

let bundle = `#!/usr/bin/env node
"use strict";
/**
 * agy-statusline (agy-hud) - Bundled standalone distribution
 * Generated by scripts/build.js from modular sources in src/*.js
 */
const __modules = {};
const __cache = {};
function __require(id) {
  if (id.startsWith("./")) {
    const name = id.slice(2).replace(/\\.js$/, "");
    if (__cache[name]) return __cache[name].exports;
    const mod = { exports: {} };
    __cache[name] = mod;
    __modules[name](mod, mod.exports, __require, __dirname, __filename);
    return mod.exports;
  }
  return require(id);
}
`;

for (const name of modules) {
  const filePath = path.join(srcDir, `${name}.js`);
  let code = fs.readFileSync(filePath, "utf8");
  code = code.replace(/^#!.*\r?\n/, "");
  code = code.replace(/^\s*"use strict";\s*\r?\n/, "");
  code = code.replace(/\brequire\s*\(/g, "__require(");
  if (name === "main") {
    code = code.replace(
      /if\s*\((?:__)?require\.main\s*===\s*module\)\s*\{[\s\S]*?\}\s*$/,
      ""
    );
  }
  bundle += `\n// ─── src/${name}.js ─────────────────────────────────────────────────────────\n`;
  bundle += `__modules[${JSON.stringify(name)}] = function(module, exports, __require, __dirname, __filename) {\n`;
  bundle += code;
  bundle += `\n};\n`;
}

bundle += `\nconst __main = __require("./main");\nmodule.exports = __main;\nif (require.main === module) {\n  __main.runCli(process.argv.slice(2)).then((code) => {\n    process.exitCode = code;\n  });\n}\n`;

fs.mkdirSync(path.dirname(distFile), { recursive: true });
fs.writeFileSync(distFile, bundle, { encoding: "utf8", mode: 0o755 });
console.log(`[build] Bundled ${modules.length} modules -> ${distFile} (${bundle.length} bytes)`);
